import math
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

import torch
from tensordict import TensorDict

import genesis as gs
from genesis.utils.geom import inv_quat, quat_to_xyz, transform_by_quat, transform_quat_by_quat


ASSET_DIR = Path(__file__).resolve().parents[2] / "genesis" / "assets" / "xml" / "unitree_g1"


def gs_rand(lower, upper, shape):
    assert lower.shape == upper.shape
    return (upper - lower) * torch.rand((*shape, *lower.shape), dtype=gs.tc_float, device=gs.device) + lower


def _read_obj_vertices(path):
    verts = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("v "):
                _, x, y, z, *_ = line.split()
                verts.append((float(x), float(y), float(z)))
    return torch.tensor(verts, dtype=gs.tc_float, device=gs.device)


def _single_mesh_obj(path):
    """PBD entities accept one mesh; merge OBJ material groups while preserving vertex order."""
    out_dir = Path(tempfile.gettempdir()) / "genesis_trampoline"
    out_dir.mkdir(parents=True, exist_ok=True)
    src_mtime = path.stat().st_mtime
    out = out_dir / f"{path.stem}_{int(src_mtime)}_singlemesh.obj"
    if out.exists() and out.stat().st_mtime >= src_mtime:
        return out

    kept = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("v ") or line.startswith("f "):
                kept.append(line)
    with open(out, "w", encoding="utf-8") as f:
        f.write("# Generated by examples/trampoline/trampoline_env.py for PBD cloth loading.\n")
        f.writelines(kept)
    return out


def _trampoline_contact_mjcf(path, foot_radius=0.025):
    """Create a temporary G1 MJCF with foot contact patches large enough for particle cloth contact."""
    out_dir = Path(tempfile.gettempdir()) / "genesis_trampoline"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{path.stem}_footpatch_r{int(foot_radius * 1000)}.xml"
    if out.exists() and out.stat().st_mtime >= path.stat().st_mtime:
        return out

    tree = ET.parse(path)
    root = tree.getroot()
    compiler = root.find("compiler")
    if compiler is not None:
        compiler.set("meshdir", str((path.parent / "assets").resolve()).replace("\\", "/"))

    for default in root.findall(".//default[@class='foot']"):
        geom = default.find("geom")
        if geom is not None:
            geom.set("size", str(foot_radius))

    patches = {
        "left_ankle_roll_link": "left",
        "right_ankle_roll_link": "right",
    }
    for body in root.findall(".//body"):
        side = patches.get(body.attrib.get("name"))
        if side is None:
            continue

        ET.SubElement(
            body,
            "geom",
            {
                "name": f"{side}_foot_box_trampoline_collision",
                "class": "collision",
                "type": "box",
                "pos": "0.04 0 -0.035",
                "size": "0.11 0.045 0.014",
                "friction": "0.9",
                "condim": "3",
                "group": "4",
                "rgba": "0 0.8 0 0.35",
            },
        )
        ET.SubElement(
            body,
            "geom",
            {
                "name": f"{side}_foot_capsule_trampoline_collision",
                "class": "collision",
                "type": "capsule",
                "fromto": "-0.055 0 -0.032 0.14 0 -0.032",
                "size": "0.025",
                "friction": "0.9",
                "condim": "3",
                "group": "4",
                "rgba": "0 0.8 0 0.25",
            },
        )

    tree.write(out, encoding="utf-8", xml_declaration=False)
    return out


class G1TrampolineEnv:
    def __init__(self, num_envs, env_cfg, obs_cfg, reward_cfg, command_cfg, show_viewer=False):
        env_cfg = dict(env_cfg)
        env_cfg.setdefault("trampoline_self_collision", False)
        env_cfg.setdefault("trampoline_rigid_friction", True)
        env_cfg["pbd_bending_iterations"] = 0

        self.num_envs = num_envs
        self.num_actions = env_cfg["num_actions"]
        self.cfg = env_cfg
        self.env_cfg = env_cfg
        self.obs_cfg = obs_cfg
        self.reward_cfg = reward_cfg
        self.command_cfg = command_cfg
        self.device = gs.device

        self.dt = env_cfg["dt"]
        self.max_episode_length = math.ceil(env_cfg["episode_length_s"] / self.dt)
        self.simulate_action_latency = env_cfg["simulate_action_latency"]
        self.obs_scales = obs_cfg["obs_scales"]
        self.reward_scales = reward_cfg["reward_scales"]

        trampoline_file = env_cfg["trampoline_file"]
        trampoline_path = ASSET_DIR / trampoline_file
        trampoline_pbd_path = _single_mesh_obj(trampoline_path)
        ring_count = env_cfg["outer_ring_vertex_counts"][trampoline_file]
        self.trampoline_ring_idx = torch.arange(ring_count, dtype=gs.tc_int, device=gs.device)
        trampoline_vertices = _read_obj_vertices(trampoline_path)
        self.trampoline_ring_targets = trampoline_vertices[:ring_count]
        trampoline_radius = torch.linalg.norm(trampoline_vertices[:, :2], dim=-1)
        trampoline_ring_radius = torch.linalg.norm(self.trampoline_ring_targets[:, :2], dim=-1).mean()
        center_vertices = trampoline_vertices[trampoline_radius < env_cfg["trampoline_center_radius"]]
        trampoline_stand_z = (
            center_vertices[:, 2].mean() if len(center_vertices) > 0 else trampoline_vertices[:, 2].mean()
        )
        self.trampoline_surface_z = float(trampoline_stand_z.item())
        base_init_pos = list(env_cfg["base_init_pos"])
        if env_cfg["base_init_pos_relative_to_trampoline"]:
            base_init_pos[2] += self.trampoline_surface_z + env_cfg["base_init_clearance"]

        self.scene = gs.Scene(
            sim_options=gs.options.SimOptions(
                dt=self.dt,
                substeps=env_cfg["substeps"],
                gravity=(0.0, 0.0, -9.81),
            ),
            rigid_options=gs.options.RigidOptions(
                enable_self_collision=False,
                max_collision_pairs=env_cfg["max_collision_pairs"],
                constraint_timeconst=env_cfg["constraint_timeconst"],
            ),
            pbd_options=gs.options.PBDOptions(
                particle_size=env_cfg["trampoline_particle_size"],
                enable_self_collision=env_cfg["trampoline_self_collision"],
                enable_rigid_friction=env_cfg["trampoline_rigid_friction"],
                lower_bound=(-2.0, -2.0, -0.2),
                upper_bound=(2.0, 2.0, 2.2),
                max_stretch_solver_iterations=env_cfg["pbd_stretch_iterations"],
                max_bending_solver_iterations=env_cfg["pbd_bending_iterations"],
            ),
            coupler_options=gs.options.LegacyCouplerOptions(
                rigid_pbd=env_cfg["enable_robot_trampoline_coupling"],
            ),
            profiling_options=gs.options.ProfilingOptions(show_FPS=False),
            viewer_options=gs.options.ViewerOptions(
                camera_pos=(2.8, -3.0, 1.7),
                camera_lookat=(0.0, 0.0, 0.75),
                camera_fov=35,
            ),
            vis_options=gs.options.VisOptions(
                rendered_envs_idx=[0],
                background_color=env_cfg["sky_background_color"],
                ambient_light=env_cfg["ambient_light"],
                plane_reflection=env_cfg["ground_reflection"],
            ),
            show_viewer=show_viewer,
        )

        self.ground = None
        if env_cfg["show_ground"]:
            self.ground = self.scene.add_entity(
                morph=gs.morphs.Plane(
                    pos=(0.0, 0.0, env_cfg["ground_z"]),
                    plane_size=env_cfg["ground_size"],
                    tile_size=env_cfg["ground_tile_size"],
                    visualization=True,
                    collision=env_cfg["ground_collision"],
                ),
                material=gs.materials.Rigid(
                    friction=env_cfg["ground_friction"],
                    needs_coup=False,
                ),
                surface=gs.surfaces.Default(color=env_cfg["ground_color"]),
            )

        self.trampoline_support = None
        if env_cfg["enable_trampoline_support"]:
            support_height = env_cfg["trampoline_support_height"]
            support_top_z = self.trampoline_surface_z + env_cfg["trampoline_support_top_offset"]
            support_radius = min(
                env_cfg["trampoline_support_radius"],
                float(trampoline_ring_radius.item()) - env_cfg["trampoline_support_edge_margin"],
            )
            self.trampoline_support = self.scene.add_entity(
                morph=gs.morphs.Cylinder(
                    radius=support_radius,
                    height=support_height,
                    pos=(0.0, 0.0, support_top_z - 0.5 * support_height),
                    fixed=True,
                    visualization=env_cfg["trampoline_support_visualization"],
                    collision=True,
                ),
                material=gs.materials.Rigid(
                    friction=env_cfg["trampoline_support_friction"],
                    needs_coup=False,
                ),
                surface=gs.surfaces.Default(color=(0.06, 0.06, 0.06, 0.25)),
            )

        robot_needs_coup = env_cfg["enable_robot_trampoline_coupling"]
        rigid_mat = gs.materials.Rigid(
            friction=env_cfg["robot_friction"],
            needs_coup=robot_needs_coup,
            coup_friction=env_cfg["robot_coup_friction"],
            coup_softness=env_cfg["robot_coup_softness"],
            coup_links=env_cfg["robot_coup_links"] if robot_needs_coup else None,
        )
        self.robot = self.scene.add_entity(
            morph=gs.morphs.MJCF(
                file=str(_trampoline_contact_mjcf(ASSET_DIR / env_cfg["robot_mjcf"], env_cfg["robot_foot_radius"]))
                if env_cfg["use_trampoline_contact_mjcf"]
                else env_cfg["robot_mjcf"],
                pos=base_init_pos,
                quat=env_cfg["base_init_quat"],
            ),
            material=rigid_mat,
        )
        self.trampoline = self.scene.add_entity(
            morph=gs.morphs.Mesh(
                file=str(trampoline_pbd_path),
                pos=(0.0, 0.0, 0.0),
                scale=1.0,
            ),
            material=gs.materials.PBD.Cloth(
                rho=env_cfg["trampoline_rho"],
                static_friction=env_cfg["trampoline_static_friction"],
                kinetic_friction=env_cfg["trampoline_kinetic_friction"],
                stretch_compliance=env_cfg["trampoline_stretch_compliance"],
                bending_compliance=env_cfg["trampoline_bending_compliance"],
                stretch_relaxation=env_cfg["trampoline_stretch_relaxation"],
                bending_relaxation=env_cfg["trampoline_bending_relaxation"],
                air_resistance=env_cfg["trampoline_air_resistance"],
            ),
            surface=gs.surfaces.Default(color=(0.08, 0.28, 0.75, 0.55), vis_mode="visual"),
        )

        self.scene.build(n_envs=num_envs)

        self.motors_dof_idx = torch.tensor(
            [self.robot.get_joint(name).dof_start for name in env_cfg["joint_names"]],
            dtype=gs.tc_int,
            device=gs.device,
        )
        self.locked_dof_idx = torch.tensor(
            [self.robot.get_joint(name).dof_start for name in env_cfg["locked_joint_names"]],
            dtype=gs.tc_int,
            device=gs.device,
        )
        self.all_actuated_dof_idx = torch.cat((self.motors_dof_idx, self.locked_dof_idx))
        self.actions_dof_idx = torch.argsort(self.motors_dof_idx)

        self.robot.set_dofs_kp([env_cfg["kp"]] * self.num_actions, self.motors_dof_idx)
        self.robot.set_dofs_kv([env_cfg["kd"]] * self.num_actions, self.motors_dof_idx)
        if len(self.locked_dof_idx) > 0:
            self.robot.set_dofs_kp([env_cfg["lock_kp"]] * len(self.locked_dof_idx), self.locked_dof_idx)
            self.robot.set_dofs_kv([env_cfg["lock_kd"]] * len(self.locked_dof_idx), self.locked_dof_idx)

        self.default_dof_pos = torch.tensor(
            [env_cfg["default_joint_angles"][name] for name in env_cfg["joint_names"]],
            dtype=gs.tc_float,
            device=gs.device,
        )
        self.locked_default_dof_pos = torch.tensor(
            [env_cfg["default_joint_angles"][name] for name in env_cfg["locked_joint_names"]],
            dtype=gs.tc_float,
            device=gs.device,
        )
        init_all_dofs = torch.tensor(
            [env_cfg["default_joint_angles"][joint.name] for joint in self.robot.joints[1:]],
            dtype=gs.tc_float,
            device=gs.device,
        )
        self.init_base_pos = torch.tensor(base_init_pos, dtype=gs.tc_float, device=gs.device)
        self.init_base_quat = torch.tensor(env_cfg["base_init_quat"], dtype=gs.tc_float, device=gs.device)
        self.inv_base_init_quat = inv_quat(self.init_base_quat)
        self.init_qpos = torch.cat((self.init_base_pos, self.init_base_quat, init_all_dofs))

        self.global_gravity = torch.tensor([0.0, 0.0, -1.0], dtype=gs.tc_float, device=gs.device)
        self.init_projected_gravity = transform_by_quat(self.global_gravity, self.inv_base_init_quat)
        self.base_height_ref = self.init_base_pos[2].clone()
        self.flight_height_target = reward_cfg["flight_height_target"]

        self.base_pos = torch.empty((num_envs, 3), dtype=gs.tc_float, device=gs.device)
        self.base_quat = torch.empty((num_envs, 4), dtype=gs.tc_float, device=gs.device)
        self.base_euler = torch.empty((num_envs, 3), dtype=gs.tc_float, device=gs.device)
        self.base_lin_vel = torch.empty((num_envs, 3), dtype=gs.tc_float, device=gs.device)
        self.base_ang_vel = torch.empty((num_envs, 3), dtype=gs.tc_float, device=gs.device)
        self.projected_gravity = torch.empty((num_envs, 3), dtype=gs.tc_float, device=gs.device)
        self.dof_pos = torch.empty((num_envs, self.num_actions), dtype=gs.tc_float, device=gs.device)
        self.dof_vel = torch.empty((num_envs, self.num_actions), dtype=gs.tc_float, device=gs.device)
        self.last_dof_vel = torch.zeros_like(self.dof_vel)
        self.actions = torch.zeros((num_envs, self.num_actions), dtype=gs.tc_float, device=gs.device)
        self.last_actions = torch.zeros_like(self.actions)
        self.phase = torch.zeros((num_envs, 2), dtype=gs.tc_float, device=gs.device)
        self.commands = torch.zeros((num_envs, command_cfg["num_commands"]), dtype=gs.tc_float, device=gs.device)
        self.rew_buf = torch.zeros((num_envs,), dtype=gs.tc_float, device=gs.device)
        self.reset_buf = torch.ones((num_envs,), dtype=gs.tc_bool, device=gs.device)
        self.episode_length_buf = torch.zeros((num_envs,), dtype=gs.tc_int, device=gs.device)
        self.max_height_buf = torch.zeros((num_envs,), dtype=gs.tc_float, device=gs.device)
        self.jump_success_buf = torch.zeros((num_envs,), dtype=gs.tc_float, device=gs.device)
        self.extras = {}

        self._fix_trampoline_outer_ring()

        self.reward_functions, self.episode_sums = {}, {}
        for name in self.reward_scales:
            self.reward_scales[name] *= self.dt
            self.reward_functions[name] = getattr(self, "_reward_" + name)
            self.episode_sums[name] = torch.zeros((num_envs,), dtype=gs.tc_float, device=gs.device)

        self.reset()

    def _fix_trampoline_outer_ring(self):
        particles = self.trampoline.get_particles_pos()
        if particles.ndim == 3:
            particles = particles[0]
        fixed = set()
        for target in self.trampoline_ring_targets:
            fixed.add(int(torch.argmin(torch.linalg.norm(particles - target, dim=-1)).item()))

        ring_radius = torch.linalg.norm(self.trampoline_ring_targets[:, :2], dim=-1).mean()
        particle_radius = torch.linalg.norm(particles[:, :2], dim=-1)
        boundary_idx = torch.nonzero(
            particle_radius >= ring_radius - self.env_cfg["trampoline_outer_fix_width"],
            as_tuple=False,
        ).flatten()
        fixed.update(int(i) for i in boundary_idx.detach().cpu().tolist())
        self.trampoline_fixed_particles = sorted(set(fixed))
        fixed_idx = torch.tensor(self.trampoline_fixed_particles, dtype=gs.tc_int, device=gs.device)
        self.trampoline.fix_particles(fixed_idx)

    def _resample_commands(self, envs_idx=None):
        period = gs_rand(
            torch.tensor(self.command_cfg["period_range"][0], dtype=gs.tc_float, device=gs.device),
            torch.tensor(self.command_cfg["period_range"][1], dtype=gs.tc_float, device=gs.device),
            (self.num_envs,),
        )
        if envs_idx is None:
            self.commands[:, 0] = period
        else:
            self.commands[:, 0] = torch.where(envs_idx, period, self.commands[:, 0])

    def step(self, actions):
        self.actions = torch.clip(actions, -self.env_cfg["clip_actions"], self.env_cfg["clip_actions"])
        exec_actions = self.last_actions if self.simulate_action_latency else self.actions
        target_dof_pos = exec_actions * self.env_cfg["action_scale"] + self.default_dof_pos
        self.robot.control_dofs_position(target_dof_pos[:, self.actions_dof_idx], self.motors_dof_idx)
        if len(self.locked_dof_idx) > 0:
            self.robot.control_dofs_position(self.locked_default_dof_pos.expand(self.num_envs, -1), self.locked_dof_idx)

        self.scene.step()

        self.episode_length_buf += 1
        self._refresh_state()

        height_above_ref = self.base_pos[:, 2] - self.base_height_ref
        self.max_height_buf = torch.maximum(self.max_height_buf, height_above_ref)
        self.jump_success_buf = torch.maximum(
            self.jump_success_buf, (height_above_ref > self.flight_height_target).float()
        )

        self.rew_buf.zero_()
        for name, reward_func in self.reward_functions.items():
            rew = reward_func() * self.reward_scales[name]
            self.rew_buf += rew
            self.episode_sums[name] += rew

        self._resample_commands(self.episode_length_buf % int(self.env_cfg["resampling_time_s"] / self.dt) == 0)
        self.reset_buf = self.episode_length_buf > self.max_episode_length
        self.reset_buf |= torch.abs(self.base_euler[:, 0]) > self.env_cfg["termination_if_roll_greater_than"]
        self.reset_buf |= torch.abs(self.base_euler[:, 1]) > self.env_cfg["termination_if_pitch_greater_than"]
        self.reset_buf |= (
            torch.linalg.norm(self.base_pos[:, :2], dim=-1) > self.env_cfg["termination_if_xy_greater_than"]
        )
        self.reset_buf |= self.base_pos[:, 2] < self.env_cfg["termination_if_base_lower_than"]
        self.reset_buf |= self.scene.rigid_solver.get_error_envs_mask()
        self.extras["time_outs"] = (self.episode_length_buf > self.max_episode_length).to(gs.tc_float)

        self._reset_idx(self.reset_buf)
        self._update_observation()

        self.last_actions.copy_(self.actions)
        self.last_dof_vel.copy_(self.dof_vel)
        return self.get_observations(), self.rew_buf, self.reset_buf, self.extras

    def _refresh_state(self):
        self.base_pos = self.robot.get_pos()
        self.base_quat = self.robot.get_quat()
        self.base_euler = quat_to_xyz(
            transform_quat_by_quat(self.inv_base_init_quat, self.base_quat), rpy=True, degrees=True
        )
        inv_base_quat = inv_quat(self.base_quat)
        self.base_lin_vel = transform_by_quat(self.robot.get_vel(), inv_base_quat)
        self.base_ang_vel = transform_by_quat(self.robot.get_ang(), inv_base_quat)
        self.projected_gravity = transform_by_quat(self.global_gravity, inv_base_quat)
        self.dof_pos = self.robot.get_dofs_position(self.motors_dof_idx)
        self.dof_vel = self.robot.get_dofs_velocity(self.motors_dof_idx)
        phase_angle = 2.0 * math.pi * self.episode_length_buf.to(gs.tc_float) * self.dt / self.commands[:, 0]
        self.phase[:, 0] = torch.sin(phase_angle)
        self.phase[:, 1] = torch.cos(phase_angle)

    def get_observations(self):
        return TensorDict({"policy": self.obs_buf}, batch_size=[self.num_envs])

    def _reset_idx(self, envs_idx=None):
        episode_max_height = self.max_height_buf.clone()
        episode_success = self.jump_success_buf.clone()

        self.robot.set_qpos(self.init_qpos, envs_idx=envs_idx, zero_velocity=True, skip_forward=True)
        if envs_idx is None:
            self.trampoline.set_position(self.trampoline._particles)
            self.trampoline.set_velocity(0.0)
            self.trampoline.process_input()
            self.trampoline.fix_particles(self.trampoline_fixed_particles)
            self.base_pos.copy_(self.init_base_pos)
            self.base_quat.copy_(self.init_base_quat)
            self.projected_gravity.copy_(self.init_projected_gravity)
            self.base_lin_vel.zero_()
            self.base_ang_vel.zero_()
            self.dof_pos.copy_(self.default_dof_pos)
            self.dof_vel.zero_()
            self.actions.zero_()
            self.last_actions.zero_()
            self.last_dof_vel.zero_()
            self.episode_length_buf.zero_()
            self.max_height_buf.zero_()
            self.jump_success_buf.zero_()
            self.reset_buf.fill_(True)
        else:
            self.base_pos[envs_idx] = self.init_base_pos
            self.base_quat[envs_idx] = self.init_base_quat
            self.projected_gravity[envs_idx] = self.init_projected_gravity
            self.base_lin_vel.masked_fill_(envs_idx[:, None], 0.0)
            self.base_ang_vel.masked_fill_(envs_idx[:, None], 0.0)
            self.dof_pos[envs_idx] = self.default_dof_pos
            self.dof_vel.masked_fill_(envs_idx[:, None], 0.0)
            self.actions.masked_fill_(envs_idx[:, None], 0.0)
            self.last_actions.masked_fill_(envs_idx[:, None], 0.0)
            self.last_dof_vel.masked_fill_(envs_idx[:, None], 0.0)
            self.episode_length_buf.masked_fill_(envs_idx, 0)
            self.max_height_buf.masked_fill_(envs_idx, 0.0)
            self.jump_success_buf.masked_fill_(envs_idx, 0.0)
            self.reset_buf.masked_fill_(envs_idx, True)

        n_envs = envs_idx.sum() if envs_idx is not None else self.num_envs
        self.extras["episode"] = {
            "max_jump_height": episode_max_height.mean()
            if envs_idx is None
            else torch.where(n_envs > 0, episode_max_height[envs_idx].sum() / n_envs, 0.0),
            "jump_success_rate": episode_success.mean()
            if envs_idx is None
            else torch.where(n_envs > 0, episode_success[envs_idx].sum() / n_envs, 0.0),
        }
        for key, value in self.episode_sums.items():
            mean = value.mean() if envs_idx is None else torch.where(n_envs > 0, value[envs_idx].sum() / n_envs, 0.0)
            self.extras["episode"]["rew_" + key] = mean / self.env_cfg["episode_length_s"]
            if envs_idx is None:
                value.zero_()
            else:
                value.masked_fill_(envs_idx, 0.0)
        self._resample_commands(envs_idx)

    def _update_observation(self):
        self.obs_buf = torch.cat(
            (
                self.base_ang_vel * self.obs_scales["ang_vel"],
                self.projected_gravity,
                self.phase,
                (self.base_pos[:, 2:3] - self.base_height_ref) * self.obs_scales["height"],
                self.base_lin_vel[:, 2:3] * self.obs_scales["lin_vel_z"],
                self.base_pos[:, :2] * self.obs_scales["xy"],
                (self.dof_pos - self.default_dof_pos) * self.obs_scales["dof_pos"],
                self.dof_vel * self.obs_scales["dof_vel"],
                self.actions,
            ),
            dim=-1,
        )

    def reset(self):
        self._reset_idx()
        self._update_observation()
        return self.get_observations()

    def _reward_jump_height(self):
        h = self.base_pos[:, 2] - self.base_height_ref
        return torch.exp(-torch.square((h - self.flight_height_target) / self.reward_cfg["height_tracking_sigma"]))

    def _reward_air_time_apex(self):
        h = self.base_pos[:, 2] - self.base_height_ref
        up = torch.clamp(h / self.flight_height_target, 0.0, 1.5)
        near_apex = torch.exp(-torch.square(self.base_lin_vel[:, 2] / self.reward_cfg["apex_vel_sigma"]))
        return up * near_apex

    def _reward_vertical_velocity(self):
        desired = self.reward_cfg["takeoff_vel"] * torch.clamp(self.phase[:, 0], min=0.0)
        return torch.exp(-torch.square((self.base_lin_vel[:, 2] - desired) / self.reward_cfg["vel_tracking_sigma"]))

    def _reward_centering(self):
        return torch.exp(-torch.sum(torch.square(self.base_pos[:, :2]), dim=-1) / self.reward_cfg["centering_sigma"])

    def _reward_upright(self):
        return torch.sum(torch.square(self.projected_gravity[:, :2]), dim=-1)

    def _reward_action_rate(self):
        return torch.sum(torch.square(self.actions - self.last_actions), dim=-1)

    def _reward_dof_acc(self):
        return torch.sum(torch.square((self.dof_vel - self.last_dof_vel) / self.dt), dim=-1)

    def _reward_similar_to_default(self):
        return torch.sum(torch.square(self.dof_pos - self.default_dof_pos), dim=-1)

    def _reward_alive(self):
        return torch.ones((self.num_envs,), dtype=gs.tc_float, device=gs.device)

    def _reward_standing_height(self):
        target_height = self.base_height_ref + self.reward_cfg["standing_height_offset"]
        height_error = self.base_pos[:, 2] - target_height
        return torch.exp(-torch.square(height_error / self.reward_cfg["standing_height_sigma"]))

    def _reward_lin_vel_xy(self):
        return torch.sum(torch.square(self.base_lin_vel[:, :2]), dim=-1)

    def _reward_lin_vel_z(self):
        return torch.square(self.base_lin_vel[:, 2])

    def _reward_ang_vel_xy(self):
        return torch.sum(torch.square(self.base_ang_vel[:, :2]), dim=-1)

    def _reward_dof_vel(self):
        return torch.sum(torch.square(self.dof_vel), dim=-1)


