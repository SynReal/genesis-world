def _demo_actions(env, mode, step):
    actions = torch.zeros((env.num_envs, env.num_actions), dtype=gs.tc_float, device=gs.device)
    if mode == "sine":
        phase = math.sin(2.0 * math.pi * step * env.dt / 0.7)
        actions[:, [0, 6]] = -0.35 * phase
        actions[:, [3, 9]] = 0.85 * phase
        actions[:, [4, 10]] = -0.45 * phase
    return actions


